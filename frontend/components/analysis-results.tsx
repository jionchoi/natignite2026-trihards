"use client"

import { AlertTriangle, CheckCircle2, Info, FileDown, Loader2 } from "lucide-react"
import { Button } from "@/components/ui/button"
import { useState } from "react"

interface Issue {
  type: "error" | "warning" | "info"
  title: string
  description: string
  regulation?: string
}

interface AnalysisResultsProps {
  issues: Issue[]
  summary: string
  isStreaming?: boolean
}

export function AnalysisResults({ issues, summary, isStreaming }: AnalysisResultsProps) {
  const [isExporting, setIsExporting] = useState(false)

  const errorCount = issues.filter(i => i.type === "error").length
  const warningCount = issues.filter(i => i.type === "warning").length
  const infoCount = issues.filter(i => i.type === "info").length

  const getIcon = (type: Issue["type"]) => {
    switch (type) {
      case "error":
        return <AlertTriangle className="w-4 h-4 sm:w-5 sm:h-5 text-destructive flex-shrink-0" />
      case "warning":
        return <AlertTriangle className="w-4 h-4 sm:w-5 sm:h-5 text-yellow-500 flex-shrink-0" />
      case "info":
        return <Info className="w-4 h-4 sm:w-5 sm:h-5 text-primary flex-shrink-0" />
    }
  }

  const getBorderColor = (type: Issue["type"]) => {
    switch (type) {
      case "error":
        return "border-l-destructive"
      case "warning":
        return "border-l-yellow-500"
      case "info":
        return "border-l-primary"
    }
  }

  const handleExportPDF = async () => {
    setIsExporting(true)
    try {
      const { jsPDF } = await import("jspdf")
      const doc = new jsPDF()
      
      // Title
      doc.setFontSize(20)
      doc.setTextColor(29, 158, 117)
      doc.text("Accessify - Accessibility Analysis Report", 20, 20)
      
      // Summary
      doc.setFontSize(12)
      doc.setTextColor(60, 60, 60)
      doc.text("Summary:", 20, 35)
      
      const summaryLines = doc.splitTextToSize(summary, 170)
      doc.setFontSize(10)
      doc.text(summaryLines, 20, 42)
      
      let yPosition = 42 + (summaryLines.length * 5) + 10
      
      // Statistics
      doc.setFontSize(12)
      doc.text(`Issues Found: ${errorCount} Critical | ${warningCount} Warnings | ${infoCount} Recommendations`, 20, yPosition)
      yPosition += 15
      
      // Issues
      issues.forEach((issue, index) => {
        if (yPosition > 270) {
          doc.addPage()
          yPosition = 20
        }
        
        const typeLabel = issue.type === "error" ? "[CRITICAL]" : issue.type === "warning" ? "[WARNING]" : "[INFO]"
        
        doc.setFontSize(11)
        doc.setTextColor(issue.type === "error" ? 220 : issue.type === "warning" ? 180 : 29, 
                         issue.type === "error" ? 53 : issue.type === "warning" ? 140 : 158, 
                         issue.type === "error" ? 69 : issue.type === "warning" ? 0 : 117)
        doc.text(`${index + 1}. ${typeLabel} ${issue.title}`, 20, yPosition)
        
        yPosition += 6
        doc.setFontSize(9)
        doc.setTextColor(80, 80, 80)
        const descLines = doc.splitTextToSize(issue.description, 165)
        doc.text(descLines, 25, yPosition)
        yPosition += (descLines.length * 4) + 3
        
        if (issue.regulation) {
          doc.setTextColor(100, 100, 100)
          doc.text(`Reference: ${issue.regulation}`, 25, yPosition)
          yPosition += 8
        }
        
        yPosition += 5
      })
      
      // Footer
      doc.setFontSize(8)
      doc.setTextColor(150, 150, 150)
      doc.text(`Generated by Accessify on ${new Date().toLocaleDateString()}`, 20, 285)
      
      doc.save("accessify-report.pdf")
    } catch (error) {
      console.error("Failed to export PDF:", error)
    } finally {
      setIsExporting(false)
    }
  }

  return (
    <div className="w-full space-y-4 sm:space-y-6 animate-slide-in-up">
      {/* Summary Card */}
      <div className="frosted-glass rounded-xl p-4 sm:p-6">
        <div className="flex flex-col sm:flex-row sm:items-start sm:justify-between gap-3 sm:gap-4 mb-4">
          <h2 className="font-serif text-xl sm:text-2xl text-foreground">Analysis Summary</h2>
          <Button 
            onClick={handleExportPDF} 
            disabled={isExporting || isStreaming}
            variant="outline"
            size="sm"
            className="gap-2 self-start sm:self-auto"
          >
            {isExporting ? (
              <Loader2 className="w-4 h-4 animate-spin" />
            ) : (
              <FileDown className="w-4 h-4" />
            )}
            <span className="hidden sm:inline">Export PDF</span>
            <span className="sm:hidden">PDF</span>
          </Button>
        </div>
        <p className="text-sm sm:text-base text-muted-foreground leading-relaxed">
          {summary}
          {isStreaming && <span className="inline-block w-2 h-4 ml-1 bg-primary animate-pulse" />}
        </p>
      </div>

      {/* Statistics */}
      <div className="grid grid-cols-3 gap-2 sm:gap-4">
        <div className="frosted-glass rounded-xl p-3 sm:p-4 text-center">
          <div className="text-xl sm:text-2xl font-bold text-destructive">{errorCount}</div>
          <div className="text-xs sm:text-sm text-muted-foreground">Critical</div>
        </div>
        <div className="frosted-glass rounded-xl p-3 sm:p-4 text-center">
          <div className="text-xl sm:text-2xl font-bold text-yellow-500">{warningCount}</div>
          <div className="text-xs sm:text-sm text-muted-foreground">Warnings</div>
        </div>
        <div className="frosted-glass rounded-xl p-3 sm:p-4 text-center">
          <div className="text-xl sm:text-2xl font-bold text-primary">{infoCount}</div>
          <div className="text-xs sm:text-sm text-muted-foreground">Info</div>
        </div>
      </div>

      {/* Compliance Score */}
      {!isStreaming && issues.length > 0 && (
        <div className="frosted-glass rounded-xl p-4 sm:p-6">
          <h3 className="font-medium text-foreground mb-3">Compliance Overview</h3>
          <div className="flex items-center gap-3 sm:gap-4">
            <div className="flex-1 h-2 sm:h-3 bg-secondary rounded-full overflow-hidden">
              <div 
                className="h-full bg-gradient-to-r from-destructive via-yellow-500 to-primary rounded-full transition-all duration-1000"
                style={{ 
                  width: `${Math.max(10, 100 - (errorCount * 20) - (warningCount * 10))}%` 
                }}
              />
            </div>
            <span className="text-base sm:text-lg font-bold text-foreground whitespace-nowrap">
              {Math.max(0, 100 - (errorCount * 20) - (warningCount * 10))}%
            </span>
          </div>
          <p className="text-xs text-muted-foreground mt-2">
            Based on ADA compliance guidelines
          </p>
        </div>
      )}

      {/* Issues List */}
      {issues.length > 0 && (
        <div className="space-y-3">
          <h3 className="font-medium text-foreground px-1">Detailed Findings</h3>
          {issues.map((issue, index) => (
            <div
              key={index}
              className={`frosted-glass rounded-xl p-3 sm:p-4 border-l-4 ${getBorderColor(issue.type)} animate-slide-in-up`}
              style={{ animationDelay: `${index * 100}ms` }}
            >
              <div className="flex items-start gap-2 sm:gap-3">
                {getIcon(issue.type)}
                <div className="flex-1 min-w-0">
                  <h4 className="font-medium text-foreground text-sm sm:text-base">{issue.title}</h4>
                  <p className="text-xs sm:text-sm text-muted-foreground mt-1 leading-relaxed">
                    {issue.description}
                  </p>
                  {issue.regulation && (
                    <div className="mt-2 flex items-center gap-2">
                      <CheckCircle2 className="w-3 h-3 text-primary flex-shrink-0" />
                      <span className="text-xs text-primary">{issue.regulation}</span>
                    </div>
                  )}
                </div>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  )
}
